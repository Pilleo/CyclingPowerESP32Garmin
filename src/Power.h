#include <cmath>
#include <cstdint>

class Power {
public:
    static auto power(const uint8_t resistanceLevel, const float cadence) -> uint16_t {
        if (cadence < 10.0F) {
            return 0;
        }

        // Get the integer and fractional parts of the cadence
        float int_part;
        float const frac_part = modff(cadence, &int_part);
        int const cadence_floor = static_cast<int>(int_part);
        int const cadence_ceil = cadence_floor + 1;

        // Lambda to get power for a given integer cadence from the table
        auto get_power_for_cadence = [&](int c) -> uint16_t {
            int cadencePointer;
            if (c <= 20) {
                cadencePointer = 0;
            } else if (c >= 100) {
                cadencePointer = 80;
            } else {
                cadencePointer = c - 20;
            }

            uint16_t p;
            if (c < 10) {
                p = 0;
            } else if (c > 100) {
                // Extrapolate for cadence > 100
                p = powerFromCadenceByLevel[80][resistanceLevel - 1] + ((c - 100) * 2);
            } else {
                p = powerFromCadenceByLevel[cadencePointer][resistanceLevel - 1];
            }
            return p;
        };

        // Get power for floor and ceil cadence
        uint16_t const power_floor = get_power_for_cadence(cadence_floor);
        uint16_t const power_ceil = get_power_for_cadence(cadence_ceil);

        // Linearly interpolate the power
        float const interpolated_power =
                power_floor + ((static_cast<float>(power_ceil) - static_cast<float>(power_floor)) * frac_part);

        return static_cast<uint16_t>(roundf(interpolated_power));
    };

private:
    static const std::array<std::array<uint16_t, 16>, 81> powerFromCadenceByLevel;
};

